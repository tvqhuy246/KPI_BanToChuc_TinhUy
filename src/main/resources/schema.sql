-- 1. Phòng chuyên môn (Departments)
CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Vị trí việc làm (Positions)
CREATE TABLE IF NOT EXISTS positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    job_description TEXT
);

-- 3. Cán bộ, công chức (Users)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(150),
    phone VARCHAR(20),
    department_id BIGINT,
    position_id BIGINT,
    role VARCHAR(50) NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    CONSTRAINT fk_user_pos FOREIGN KEY (position_id) REFERENCES positions(id) ON DELETE SET NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('ADMIN', 'LANH_DAO_BAN', 'TRUONG_PHONG', 'CHUYEN_VIEN')),
    CONSTRAINT chk_user_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

-- 4. Bộ tiêu chí định lượng KPI (KpiCriteria)
CREATE TABLE IF NOT EXISTS kpi_criteria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    group_type VARCHAR(10) NOT NULL,
    max_score DOUBLE NOT NULL,
    scoring_guide TEXT,
    target_role VARCHAR(50) DEFAULT 'ALL',
    CONSTRAINT chk_criteria_group CHECK (group_type IN ('A', 'B', 'C')),
    CONSTRAINT chk_criteria_max_score CHECK (max_score > 0 AND max_score <= 100)
);

-- 5. Bảng Nhiệm vụ công tác (Tasks) - Đầy đủ 4 loại hình công tác & Ràng buộc toàn vẹn
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(300) NOT NULL,
    description TEXT,
    assigned_to BIGINT NOT NULL,
    assigned_by BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    criteria_id BIGINT,
    
    -- Phân loại nghiệp vụ theo Quy định số 01-QĐ/BTCTU
    task_type VARCHAR(50) DEFAULT 'VAN_BAN',
    complexity VARCHAR(30) DEFAULT 'TRUNG_BINH',
    
    -- Nghiệp vụ đặc thù
    speech_approved BOOLEAN DEFAULT FALSE,
    field_trip_location VARCHAR(255),
    field_trip_result TEXT,
    office_discipline_note TEXT,
    
    priority VARCHAR(20) DEFAULT 'NORMAL',
    start_date DATE NOT NULL,
    due_date DATE NOT NULL,
    completed_date DATE,
    progress INT DEFAULT 0,
    status VARCHAR(30) DEFAULT 'IN_PROGRESS',
    evidence_text TEXT,
    weight DOUBLE DEFAULT 1.0,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_task_assignee FOREIGN KEY (assigned_to) REFERENCES users(id),
    CONSTRAINT fk_task_assigner FOREIGN KEY (assigned_by) REFERENCES users(id),
    CONSTRAINT fk_task_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_task_criteria FOREIGN KEY (criteria_id) REFERENCES kpi_criteria(id),
    CONSTRAINT chk_task_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT chk_task_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'COMPLETED', 'OVERDUE')),
    CONSTRAINT chk_task_type CHECK (task_type IN ('VAN_BAN', 'HOP', 'CONG_TAC', 'CONG_SO')),
    CONSTRAINT chk_task_complexity CHECK (complexity IN ('DE', 'TRUNG_BINH', 'KHO', 'DAC_BIET')),
    CONSTRAINT chk_task_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT chk_task_weight CHECK (weight > 0)
);

-- 6. Nhật ký công việc hằng ngày & Báo cáo tuần (WorkLogs)
CREATE TABLE IF NOT EXISTS work_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    task_id BIGINT,
    log_date DATE NOT NULL,
    week_number INT NOT NULL,
    month_val VARCHAR(20) NOT NULL,
    work_content TEXT NOT NULL,
    hours_spent DOUBLE DEFAULT 8.0,
    result_status VARCHAR(50),
    supervisor_comment TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_log_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE SET NULL,
    CONSTRAINT chk_log_hours CHECK (hours_spent >= 0 AND hours_spent <= 24),
    CONSTRAINT chk_log_week CHECK (week_number BETWEEN 1 AND 53)
);

-- 7. Đánh giá Cán bộ cá nhân (Evaluations)
CREATE TABLE IF NOT EXISTS evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    period_type VARCHAR(20) NOT NULL,
    period_value VARCHAR(50) NOT NULL,
    self_score DOUBLE DEFAULT 0.0,
    manager_score DOUBLE DEFAULT 0.0,
    final_score DOUBLE DEFAULT 0.0,
    ranking VARCHAR(50),
    self_notes TEXT,
    manager_notes TEXT,
    leader_notes TEXT,
    status VARCHAR(30) DEFAULT 'DRAFT',
    evaluated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    approved_by BIGINT,
    approved_at TIMESTAMP,
    CONSTRAINT fk_eval_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_eval_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_eval_approver FOREIGN KEY (approved_by) REFERENCES users(id),
    CONSTRAINT chk_eval_period_type CHECK (period_type IN ('MONTH', 'QUARTER', 'YEAR')),
    CONSTRAINT chk_eval_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'REVIEWED', 'APPROVED')),
    CONSTRAINT chk_eval_self_score CHECK (self_score BETWEEN 0 AND 100),
    CONSTRAINT chk_eval_manager_score CHECK (manager_score IS NULL OR manager_score BETWEEN 0 AND 100),
    CONSTRAINT chk_eval_final_score CHECK (final_score IS NULL OR final_score BETWEEN 0 AND 100)
);

-- 8. Ban Tổ chức đánh giá Phòng chuyên môn (DepartmentEvaluations)
-- Cột tính toán tự động GENERATED ALWAYS AS theo thang điểm Quy định 01-QĐ/BTCTU:
-- Tiến độ (30đ) + Chất lượng (30đ) + Chuyển đổi số (15đ) + Kỷ cương (15đ) + Chuyên viên (10đ) = 100đ
CREATE TABLE IF NOT EXISTS department_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    period_type VARCHAR(20) NOT NULL,
    period_value VARCHAR(50) NOT NULL,
    plan_score DOUBLE DEFAULT 0.0,
    quality_score DOUBLE DEFAULT 0.0,
    it_digital_score DOUBLE DEFAULT 0.0,
    discipline_score DOUBLE DEFAULT 0.0,
    avg_staff_score DOUBLE DEFAULT 0.0,
    total_score DOUBLE GENERATED ALWAYS AS (plan_score + quality_score + it_digital_score + discipline_score + avg_staff_score),
    ranking VARCHAR(50),
    leader_feedback TEXT,
    evaluated_by BIGINT,
    evaluated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dept_eval_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_dept_eval_leader FOREIGN KEY (evaluated_by) REFERENCES users(id),
    CONSTRAINT chk_dept_period_type CHECK (period_type IN ('MONTH', 'QUARTER', 'YEAR')),
    CONSTRAINT chk_dept_plan_score CHECK (plan_score BETWEEN 0 AND 30),
    CONSTRAINT chk_dept_quality_score CHECK (quality_score BETWEEN 0 AND 30),
    CONSTRAINT chk_dept_digital_score CHECK (it_digital_score BETWEEN 0 AND 15),
    CONSTRAINT chk_dept_discipline_score CHECK (discipline_score BETWEEN 0 AND 15),
    CONSTRAINT chk_dept_avg_staff_score CHECK (avg_staff_score BETWEEN 0 AND 10)
);

-- 9. Chi tiết chấm điểm từng tiêu chí (EvaluationDetails)
CREATE TABLE IF NOT EXISTS evaluation_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL,
    criteria_id BIGINT NOT NULL,
    self_points DOUBLE DEFAULT 0.0,
    manager_points DOUBLE DEFAULT 0.0,
    final_points DOUBLE DEFAULT 0.0,
    notes TEXT,
    CONSTRAINT fk_detail_eval FOREIGN KEY (evaluation_id) REFERENCES evaluations(id) ON DELETE CASCADE,
    CONSTRAINT fk_detail_crit FOREIGN KEY (criteria_id) REFERENCES kpi_criteria(id),
    CONSTRAINT chk_detail_self_points CHECK (self_points BETWEEN 0 AND 100),
    CONSTRAINT chk_detail_manager_points CHECK (manager_points IS NULL OR manager_points BETWEEN 0 AND 100),
    CONSTRAINT chk_detail_final_points CHECK (final_points IS NULL OR final_points BETWEEN 0 AND 100)
);

