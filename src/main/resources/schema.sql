-- =========================================================================
-- HỆ THỐNG CƠ SỞ DỮ LIỆU ĐÁNH GIÁ KPI - BAN TỔ CHỨC TỈNH ỦY ĐẮK LẮK
-- Căn cứ pháp lý: Quy định số 01-QĐ/BTCTU ngày 28/11/2025
-- Phiên bản: Enterprise CSDL v2.0 (Chuẩn hóa Schema, Ràng buộc, Soft-Delete & Analytics Views)
