-- =========================================================================
-- KHUNG NHÌN PHÂN TÍCH THÔNG MINH (ANALYTICS VIEWS)
-- =========================================================================
-- View 1: Cảnh báo nhiệm vụ quá hạn hoặc sắp đến hạn trong vòng 48h
CREATE OR REPLACE VIEW v_task_overdue_warning AS
SELECT 
    t.id AS task_id,
    t.title,
    t.task_type,
    t.priority,
    t.progress,
    t.status,
    t.due_date,
    u.full_name AS assignee_name,
    d.name AS department_name,
    DATEDIFF('DAY', CURRENT_DATE, t.due_date) AS days_remaining
FROM tasks t
JOIN users u ON t.assigned_to = u.id
JOIN departments d ON t.department_id = d.id
WHERE t.status != 'COMPLETED';

-- View 2: Tổng hợp hiệu suất KPI phòng ban
CREATE OR REPLACE VIEW v_department_kpi_summary AS
SELECT 
    d.id AS department_id,
    d.name AS department_name,
    COUNT(t.id) AS total_tasks,
    COUNT(CASE WHEN t.status = 'COMPLETED' THEN 1 END) AS completed_tasks,
    ROUND(AVG(CAST(t.progress AS DOUBLE)), 1) AS avg_progress
FROM departments d
LEFT JOIN tasks t ON d.id = t.department_id
GROUP BY d.id, d.name;

